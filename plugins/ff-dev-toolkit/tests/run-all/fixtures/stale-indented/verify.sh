#!/usr/bin/env bash
# 鮮度マーカーを**インデント付き**で出して赤で終わる疑似 suite。
# 他 suite の出力を引用するダンプ（`sed 's/^/    | /'` 等）はこの repo の標準書式なので、
# 分類が部分一致へ緩むと、引用された鮮度マーカーで**変更起因の赤が鮮度として報告される**。
# 行頭アンカーが効いている限り、この suite は stale へ分類されない。
echo "    | ✗ 鮮度: 別 suite の出力を引用しただけの行（分類対象ではない）" >&2
echo "  ✗ 本物の回帰: 変更起因の赤" >&2
exit 1
